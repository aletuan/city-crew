// FROZEN — HCMC-only bootstrap pipeline (the bbox check below is HCMC by
// design). The DB is the source of truth; new cities come in via the
// dashboard's Scan city / Add place flows. Kept for provenance only.
//
// Merge seeds/curation.json over review/places.review.json, validate, and emit
// idempotent upsert SQL for Supabase (places, place_photos, collections).
//
// The SQL goes to data/snapshot/upsert.sql — run it with the Supabase MCP
// execute_sql tool (or psql with a service-role connection). Writing SQL instead
// of calling the API keeps the service-role key out of this repo entirely.
//
// Usage: node scripts/upsert-supabase.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DATA_DIR = join(dirname(fileURLToPath(import.meta.url)), '..');
const VIBES = ['cafes', 'food_tour', 'outdoors', 'views', 'culture', 'shopping', 'nightlife', 'chill'];

const review = JSON.parse(readFileSync(join(DATA_DIR, 'review', 'places.review.json'), 'utf8'));
const curation = JSON.parse(readFileSync(join(DATA_DIR, 'seeds', 'curation.json'), 'utf8'));
const { collections } = JSON.parse(readFileSync(join(DATA_DIR, 'seeds', 'collections.json'), 'utf8'));

// Merge curated fields over fetched data
const errors = [];
const places = [];
for (const [slug, fetched] of Object.entries(review.places)) {
  const curated = curation.places[slug];
  if (!curated) { errors.push(`${slug}: no curation entry`); continue; }
  if (fetched.fetch_failed) { errors.push(`${slug}: fetch failed, cannot publish`); continue; }
  const p = { ...fetched, ...curated, needs_review: false };

  if (!p.name_en || !p.name_vi) errors.push(`${slug}: missing bilingual name`);
  if (!p.desc_en || !p.desc_vi) errors.push(`${slug}: missing bilingual description`);
  if (!(p.lat > 10.3 && p.lat < 11.2 && p.lng > 106.3 && p.lng < 107.1)) errors.push(`${slug}: coords outside HCMC bbox`);
  if (!p.vibe_tags.every((t) => VIBES.includes(t))) errors.push(`${slug}: unknown vibe tag`);
  if (!p.photos?.length) errors.push(`${slug}: no photos`);
  if (!['food', 'out'].includes(p.category)) errors.push(`${slug}: bad category`);
  places.push(p);
}

for (const c of collections) {
  for (const slug of c.places) {
    if (!review.places[slug]) errors.push(`collection ${c.slug}: unknown place ${slug}`);
  }
}

if (errors.length) {
  console.error('Validation failed:\n' + errors.map((e) => `  - ${e}`).join('\n'));
  process.exit(1);
}

const q = (v) => {
  if (v === null || v === undefined || v === '') return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const qArr = (a) => `array[${a.map(q).join(',')}]::text[]`;
const qJson = (v) => (v == null ? 'null' : `${q(JSON.stringify(v))}::jsonb`);

let sql = '-- Generated by upsert-supabase.mjs — idempotent upsert of curated demo data\nbegin;\n\n';

for (const p of places) {
  sql += `insert into places (slug, google_place_id, name_en, name_vi, category, is_featured, vibe_tags,
  neighborhood_en, neighborhood_vi, address, lat, lng, rating, rating_count,
  price_level, price_display, price_vnd, duration_min, duration_max,
  desc_en, desc_vi, emoji, opening_hours, website, phone, saved_count, is_published, updated_at)
values (${q(p.slug)}, ${q(p.google_place_id)}, ${q(p.name_en)}, ${q(p.name_vi)}, ${q(p.category)}, ${p.is_featured}, ${qArr(p.vibe_tags)},
  ${q(p.neighborhood_en)}, ${q(p.neighborhood_vi)}, ${q(p.address)}, ${p.lat}, ${p.lng}, ${q(p.rating)}, ${q(p.rating_count)},
  ${q(p.price_level)}, ${q(p.price_display)}, ${q(p.price_vnd)}, ${q(p.duration_min)}, ${q(p.duration_max)},
  ${q(p.desc_en)}, ${q(p.desc_vi)}, ${q(p.emoji)}, ${qJson(p.opening_hours)}, ${q(p.website)}, ${q(p.phone)}, ${p.saved_count}, true, now())
on conflict (slug) do update set
  google_place_id = excluded.google_place_id, name_en = excluded.name_en, name_vi = excluded.name_vi,
  category = excluded.category, is_featured = excluded.is_featured, vibe_tags = excluded.vibe_tags,
  neighborhood_en = excluded.neighborhood_en, neighborhood_vi = excluded.neighborhood_vi, address = excluded.address,
  lat = excluded.lat, lng = excluded.lng, rating = excluded.rating, rating_count = excluded.rating_count,
  price_level = excluded.price_level, price_display = excluded.price_display, price_vnd = excluded.price_vnd,
  duration_min = excluded.duration_min, duration_max = excluded.duration_max,
  desc_en = excluded.desc_en, desc_vi = excluded.desc_vi, emoji = excluded.emoji,
  opening_hours = excluded.opening_hours, website = excluded.website, phone = excluded.phone,
  saved_count = excluded.saved_count, is_published = true, updated_at = now();\n\n`;

  sql += `delete from place_photos where place_id = (select id from places where slug = ${q(p.slug)});\n`;
  for (const [i, ph] of p.photos.entries()) {
    sql += `insert into place_photos (place_id, photo_ref, photo_uri, width_px, height_px, attribution_name, attribution_uri, sort_order, is_cover)
select id, ${q(ph.photo_ref)}, ${q(ph.photo_uri)}, ${q(ph.width_px)}, ${q(ph.height_px)}, ${q(ph.attribution_name)}, ${q(ph.attribution_uri)}, ${i}, ${ph.is_cover === true}
from places where slug = ${q(p.slug)};\n`;
  }
  sql += '\n';
}

for (const c of collections) {
  sql += `insert into collections (slug, title_en, title_vi, desc_en, desc_vi, curator_handle, is_public, sort_order)
values (${q(c.slug)}, ${q(c.title_en)}, ${q(c.title_vi)}, ${q(c.desc_en)}, ${q(c.desc_vi)}, ${q(c.curator_handle)}, true, ${c.sort_order})
on conflict (slug) do update set
  title_en = excluded.title_en, title_vi = excluded.title_vi, desc_en = excluded.desc_en, desc_vi = excluded.desc_vi,
  curator_handle = excluded.curator_handle, is_public = true, sort_order = excluded.sort_order;\n`;
  sql += `update collections set cover_photo_id = (
  select ph.id from place_photos ph join places p on p.id = ph.place_id
  where p.slug = ${q(c.cover)} and ph.is_cover limit 1
) where slug = ${q(c.slug)};\n`;
  sql += `delete from collection_places where collection_id = (select id from collections where slug = ${q(c.slug)});\n`;
  for (const [i, slug] of c.places.entries()) {
    sql += `insert into collection_places (collection_id, place_id, sort_order)
select c.id, p.id, ${i} from collections c, places p where c.slug = ${q(c.slug)} and p.slug = ${q(slug)};\n`;
  }
  sql += '\n';
}

sql += 'commit;\n';

const out = join(DATA_DIR, 'snapshot', 'upsert.sql');
writeFileSync(out, sql);

// Also persist the merged, curation-applied review file so it stays the
// canonical human-editable record.
for (const p of places) review.places[p.slug] = p;
writeFileSync(join(DATA_DIR, 'review', 'places.review.json'), JSON.stringify(review, null, 2));

console.log(`OK: ${places.length} places, ${collections.length} collections → ${out}`);
